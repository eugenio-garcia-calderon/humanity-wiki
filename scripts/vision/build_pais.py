"""Country models (España) for the core sectors -> public/vision/paises.js, and their
patas become the parts (subtemas) of those sectors in data.js, with their retos/soluciones/
proyectos added at scale «país». Always rebuilds from research/pais/data_base.js."""
import json, os, re, sys
R = sys.argv[1] if len(sys.argv) > 1 else '/home/claude/research/pais'
V = '/home/claude/humanity-wiki/public/vision'
base = open('/home/claude/research/pais/data_base.js').read()
head = base[:base.index('[')]
data = json.loads(base[base.index('['):base.rindex(']') + 1])

def web(u):
    if not u: return None
    u = re.sub(r'\s*\(.*\)\s*$', '', str(u)).strip()
    return u if u.startswith('http') else None

modelos = {}
for s in data:
    f = f"{R}/{s['id']}.json"
    if not os.path.exists(f): continue
    m = json.load(open(f))
    patas = m['patas']
    ids = {p['id'] for p in patas}
    s['subtemas'] = [{'id': p['id'], 'nombre': p['nombre']} for p in patas]
    # existing items: move them to the patas the researcher chose
    reas = m.get('reasignacion', {})
    norm = lambda t: re.sub(r'\W+', ' ', (t or '').lower()).strip()
    reas_n = {norm(k): [x for x in v if x in ids] for k, v in reas.items()}
    for k in ('retos', 'soluciones', 'proyectos'):
        for x in s[k]:
            x['subtemas'] = reas_n.get(norm(x.get('titulo') or x.get('nombre')), [])
    for b in s['vision']['bloques']: b['subtemas'] = []
    # the patas' own items, at country scale
    vistos = {norm(x.get('titulo') or x.get('nombre')) for k in ('retos', 'soluciones', 'proyectos') for x in s[k]}
    for p in patas:
        for r in p.get('retos', []):
            if norm(r['titulo']) in vistos: continue
            s['retos'].append({'ambito': 'España', 'titulo': r['titulo'], 'texto': r['descripcion'], 'fuente': web(r.get('fuente_url')), 'escalas': ['pais'], 'subtemas': [p['id']]})
        for r in p.get('soluciones', []):
            if norm(r['titulo']) in vistos: continue
            s['soluciones'].append({'ambito': 'España', 'titulo': r['titulo'], 'texto': r['descripcion'], 'fuente': web(r.get('fuente_url')), 'escalas': ['pais'], 'subtemas': [p['id']]})
        for r in p.get('proyectos', []):
            if norm(r['nombre']) in vistos: continue
            s['proyectos'].append({'nombre': r['nombre'], 'lugar': r.get('lugar'), 'tipo': None, 'texto': r['descripcion'], 'web': web(r.get('web')), 'fuente': None,
                                   'escalas': ['pais'] if 'españa' in (r.get('lugar') or '').lower() or not r.get('lugar') else ['pais', 'planeta'], 'subtemas': [p['id']]})
    modelos[s['id']] = {
        'vision': m['vision_general'],
        'patas': [{k: p.get(k) for k in ('id', 'nombre', 'que_es', 'actual', 'ideal', 'equilibrio')} |
                  {'indicadores': [{**i, 'fuente_url': web(i.get('fuente_url'))} for i in p.get('indicadores', [])]} for p in patas],
        'flujos': [f for f in m.get('flujos', []) if f['de'] in ids and f['a'] in ids],
    }
    print(s['id'], len(patas), 'patas', len(s['retos']), 'retos', len(s['soluciones']), 'sol', len(s['proyectos']), 'proy',
          'sin pata:', sum(1 for k in ('retos','soluciones','proyectos') for x in s[k] if not x.get('subtemas')))

open(f'{V}/data.js', 'w').write(head + json.dumps(data, ensure_ascii=False, indent=1) + ';\n')
paises = {'es': {'nombre': 'España', 'modelos': modelos}}
open(f'{V}/paises.js', 'w').write('// Country-scale models: each core sector split into its «patas», today vs ideal. Generated by build_pais.py.\n'
                                  'const PAISES = ' + json.dumps(paises, ensure_ascii=False, indent=1) + ';\n')
